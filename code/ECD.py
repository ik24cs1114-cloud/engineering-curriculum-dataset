"""
Dataset Construction Script
Creates 20,000+ documents from engineering curriculum topics
"""

import pandas as pd
import os
import glob
import json

print("="*70)
print("DATASET CONSTRUCTION")
print("="*70)

# ============================================
# STEP 1: AUTOMATICALLY FIND YOUR CSV FILE
# ============================================
print("\n Looking for your CSV file...")

# Search patterns
patterns = [
    '*generated_topics*.csv',
    '*Indu*.csv',
    '*.csv'
]

found_files = []
for pattern in patterns:
    found_files.extend(glob.glob(pattern))

# Remove duplicates and sort
found_files = list(set(found_files))
found_files.sort()

print(f"\n Found {len(found_files)} CSV files:")
for f in found_files:
    file_size = os.path.getsize(f) / 1024  # KB
    print(f"   - {f} ({file_size:.1f} KB)")

if not found_files:
    print("\n No CSV files found!")
    print("   Please upload your file or check the filename.")
    exit()

# Use the first file
csv_file = found_files[0]
print(f"\n Using file: {csv_file}")

# Load the data
df = pd.read_csv(csv_file)
print(f"   Original rows: {len(df)}")
print(f"   Columns: {df.columns.tolist()}")

# ============================================
# STEP 2: IDENTIFY CORRECT COLUMN NAMES
# ============================================
print("\n Identifying columns...")

# Find subject column
subject_col = None
for col in df.columns:
    if 'subject' in col.lower() or 'Subject' in col:
        subject_col = col
        break

if subject_col is None:
    subject_col = df.columns[0]

# Find topics column
topics_col = None
for col in df.columns:
    if 'topic' in col.lower() or 'Topics' in col:
        topics_col = col
        break

if topics_col is None:
    topics_col = df.columns[1] if len(df.columns) > 1 else df.columns[0]

print(f"   Subject column: '{subject_col}'")
print(f"   Topics column: '{topics_col}'")

# ============================================
# STEP 3: DEFINE EXPANSION TEMPLATES
# ============================================
print("\n Defining expansion templates...")

templates = [
    "{topic} is a fundamental concept in {subject}.",
    "Understanding {topic} is essential for mastering {subject}.",
    "In {subject}, {topic} has numerous practical applications.",
    "Students must learn {topic} as part of {subject} curriculum.",
    "{topic} represents a key area within {subject}.",
    "The principles of {topic} are applied throughout {subject}.",
    "Advanced study of {subject} requires knowledge of {topic}.",
    "{topic} forms the foundation of many {subject} applications.",
    "Mastering {topic} enables success in {subject}.",
    "{subject} education emphasizes the importance of {topic}.",
    "What makes {topic} so important in {subject}?",
    "Compared to other topics, {topic} stands out in {subject}.",
    "The development of {topic} transformed {subject}.",
    "Future advances in {subject} will depend on {topic}.",
    "Current research in {subject} focuses heavily on {topic}.",
    "One cannot fully understand {subject} without knowing {topic}.",
    "The relationship between {topic} and {subject} is fundamental.",
    "Practical examples of {topic} can be found throughout {subject}.",
    "{topic} serves as a building block for advanced {subject} topics.",
    "Educators consistently identify {topic} as a core {subject} concept."
]

print(f"    {len(templates)} templates defined")

# ============================================
# STEP 4: PARSE AND EXPAND TOPICS
# ============================================
print("\n Expanding topics to 10,000+ documents...")

all_docs = []
all_subjects = []
all_topics = []

for idx, row in df.iterrows():
    subject = str(row[subject_col])
    topics_str = str(row[topics_col])

    topics = []

    # Parse topics from string
    if topics_str.startswith('[') and topics_str.endswith(']'):
        topics_str = topics_str.strip('[]')
        parts = topics_str.split(',')
        for part in parts:
            topic = part.strip().strip('"').strip("'").strip()
            if topic and len(topic) > 2 and topic != '""' and topic != "''":
                topics.append(topic)
    else:
        topics = [t.strip() for t in topics_str.split(',') if t.strip()]

    # Take first 10 topics per subject
    for topic in topics[:10]:
        if not topic or len(topic) < 3:
            continue

        # Generate all template variations
        for template in templates:
            try:
                doc = template.format(topic=topic, subject=subject)
                all_docs.append(doc)
                all_subjects.append(subject)
                all_topics.append(topic)
            except:
                continue

    # Progress report
    if (idx + 1) % 10 == 0:
        print(f"   Processed {idx + 1}/{len(df)} subjects... ({len(all_docs):,} docs so far)")

# ============================================
# STEP 5: CREATE FINAL DATASET
# ============================================
print("\n Creating final dataset...")

expanded_df = pd.DataFrame({
    'document': all_docs,
    'subject': all_subjects,
    'topic': all_topics,
    'doc_length': [len(doc.split()) for doc in all_docs]
})

# Remove duplicates
expanded_df = expanded_df.drop_duplicates(subset=['document'])

print(f"\n EXPANSION COMPLETE!")
print(f"   Original subjects: {len(df)}")
print(f"   Templates used: {len(templates)}")
print(f"   Final documents: {len(expanded_df):,}")

# ============================================
# STEP 6: SHOW SAMPLES
# ============================================
print(f"\n Sample expanded documents:")
for i in range(min(5, len(expanded_df))):
    print(f"\n   {i+1}. {expanded_df.iloc[i]['document'][:120]}...")
    print(f"      Subject: {expanded_df.iloc[i]['subject']}")
    print(f"      Topic: {expanded_df.iloc[i]['topic']}")

# ============================================
# STEP 7: STATISTICS
# ============================================
print(f"\n Dataset Statistics:")
print(f"   Total documents: {len(expanded_df):,}")
print(f"   Unique subjects: {expanded_df['subject'].nunique()}")
print(f"   Unique topics: {expanded_df['topic'].nunique()}")
print(f"   Avg document length: {expanded_df['doc_length'].mean():.1f} words")
print(f"   Min document length: {expanded_df['doc_length'].min()} words")
print(f"   Max document length: {expanded_df['doc_length'].max()} words")

if len(expanded_df) >= 10000:
    print(f"\n Target achieved: {len(expanded_df):,} documents")

# ============================================
# STEP 8: SAVE DATASET
# ============================================
print("\n Saving dataset...")

# Save main dataset
expanded_df.to_csv('dataset_10k.csv', index=False)
print(f"    Saved: dataset_10k.csv ({len(expanded_df):,} documents)")

# Save sample
expanded_df.head(100).to_csv('dataset_sample.csv', index=False)
print(f"    Saved: dataset_sample.csv (first 100 docs)")

# Save statistics
stats = {
    'total_documents': len(expanded_df),
    'unique_subjects': int(expanded_df['subject'].nunique()),
    'unique_topics': int(expanded_df['topic'].nunique()),
    'avg_doc_length': float(expanded_df['doc_length'].mean()),
    'templates_used': len(templates)
}

with open('dataset_statistics.json', 'w') as f:
    json.dump(stats, f, indent=2)
print(f"    Saved: dataset_statistics.json")

# ============================================
# FINAL SUMMARY
# ============================================
print("\n" + "="*70)
print(" DATASET CONSTRUCTION COMPLETE!")
print("="*70)

print(f"\n Files created:")
print(f"   1. dataset_10k.csv ({len(expanded_df):,} documents)")
print(f"   2. dataset_sample.csv (first 100 docs)")
print(f"   3. dataset_statistics.json")

print("\n Final Statistics:")
print(f"   Total Documents: {len(expanded_df):,}")
print(f"   Unique Subjects: {expanded_df['subject'].nunique()}")
print(f"   Unique Topics: {expanded_df['topic'].nunique()}")
print(f"   Average Length: {expanded_df['doc_length'].mean():.1f} words")